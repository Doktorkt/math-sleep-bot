# Путь к файлу, где будут храниться ваши личные дописки
USER_TERMS_FILE = os.path.expanduser('~/.user_terms.txt')

# Загружаем ваши личные термины, если они есть
if os.path.exists(USER_TERMS_FILE):
    with open(USER_TERMS_FILE, 'r', encoding='utf-8') as f:
        for line in f:
            if " | " in line:
                cmd, desc = line.strip().split(" | ", 1)
                data["МОИ НОВЫЕ ТЕРМИНЫ 🚀"].append((cmd, desc))

# Если передан аргумент "добавить"
if len(sys.argv) > 1 and sys.argv[1] == "добавить":
    if len(sys.argv) < 4:
        print("\n❌ Ошибка! Формат: словарь добавить 'команда' 'описание'\n")
        sys.exit()
    new_cmd = sys.argv[2]
    new_desc = sys.argv[3]
    
    with open(USER_TERMS_FILE, 'a', encoding='utf-8') as f:
        f.write(f"{new_cmd} | {new_desc}\n")
    print(f"\n✅ Успешно добавлено: {new_cmd} -> {new_desc}\n")
    sys.exit()

# Обычный вывод списка
